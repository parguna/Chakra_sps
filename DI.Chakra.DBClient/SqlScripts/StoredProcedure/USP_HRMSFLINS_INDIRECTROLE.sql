/*
NAME		:	DBO.USP_HRMSFLINS_INDIRECTROLE
AUTHOR		:	SIVANANDAN R
DESCRIPTION	:	USED TO FETCH ROLE WHICH ARE NOT LINKED TO ANY BUSINESSROLE.MAINLY FOR ATTESTATION

EXAMPLE: 
	DECLARE @AcountReconId BIGINT=31950
	declare @APPLICATIONTYPE INT=3
	EXEC DBO.USP_HRMSFLINS_INDIRECTROLE @AcountReconId,@APPLICATIONTYPE
*/
ALTER PROC DBO.USP_HRMSFLINS_INDIRECTROLE
(
@AccountReconId BIGINT,
@APPLICATIONTYPE INT
)
AS
BEGIN

		SET NOCOUNT ON;

		DECLARE @ENDPOINTSYSTEMID BIGINT
		DECLARE @BUSINESSROLE VARCHAR(512)=''
		DECLARE @COMPANY VARCHAR(MAX)=''
		
		SELECT @ENDPOINTSYSTEMID = Id FROM DI_M_EndpointSystem WHERE ApplicationType = @APPLICATIONTYPE

		DECLARE @TOTAL BIGINT
		DECLARE @RUNNING_SEQ BIGINT=1

		DECLARE @TBLTEMP TABLE(Id INT Identity(1,1), BusinessRole varchar(2048) null,COMPANIES varchar(max) null)
		
		INSERT INTO @TBLTEMP(BusinessRole,COMPANIES)
		SELECT 
		--IDENTITY(INT,1,1) AS Id,
		USR.BusinessRole,USR.Company as COMPANIES
		FROM DBO.VWHRMSFLIN_USER_MAIN_BUSINESSROLE USR
		WHERE USR.AccountReconcilationId = @AccountReconId AND ISNULL(USR.BusinessRole,'') !=''
		ORDER BY BusinessRole

		SET @TOTAL = @@ROWCOUNT

		DECLARE @TBLFLINSROLE TABLE (TechnicalRule varchar(2000) null,[Type] varchar(100) null,Businessrole varchar(2048) null,Entitlement varchar(512) null,Description varchar(2000) null, ValidTo DateTime Null, LastAttestedOn Datetime NULL)
		
		WHILE (@TOTAL >= @RUNNING_SEQ)
		BEGIN
			
				
				SELECT @BUSINESSROLE = BusinessRole, @COMPANY = COMPANIES FROM @TBLTEMP WHERE ID = @RUNNING_SEQ
		
				INSERT INTO @TBLFLINSROLE(TechnicalRule,[Type],Businessrole,Entitlement,Description,ValidTo,LastAttestedOn)
				EXEC  DBO.USP_HRMSFLINS_GETTECHNICALROLEFROM_BUSINESSROLE @ENDPOINTSYSTEMID,@AccountReconId,@BUSINESSROLE,@COMPANY

				SET @RUNNING_SEQ = @RUNNING_SEQ + 1
		END



		SELECT E.Id,E.EntitlementId,E.EndpointUserId,E.Entitlement,R.ROLE_CODE AS Description,E.ValidToDate,E.LastAttestedOn 
		FROM dbo.DI_M_EntitlementReconcilation E WITH(NOLOCK) INNER JOIN DI_SAP_ROLEINFO R on E.Entitlement = R.ROLE_CODE WHERE  E.EndpointSystemId = @ENDPOINTSYSTEMID  AND R.EndpointSystemId = @ENDPOINTSYSTEMID AND AccountReconcilationId = @AccountReconId AND IsDeleted = 0 AND Entitlement NOT IN(
		SELECT Entitlement FROM @TBLFLINSROLE WHERE Entitlement IS NOT NULL
		) ORDER BY ENTITLEMENT

		--DROP TABLE #TBLFLINSROLE
		--DROP TABLE #TBLTEMP

END