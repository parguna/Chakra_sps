CREATE PROC DBO.USP_MSSL_EBS_INDIRECTROLE
(
@ENDPOINTSYSTEMID BIGINT,
@ACCOUNTRECONID BIGINT
)
AS
BEGIN
			SELECT R.Id,R.EndPointSystemId,U.Id as EndpointUserId,R.ROLE_CODE as BusinessRole,R.ROLE_DESC as Description,
			CASE WHEN ISDATE(UR.Role_ToDate)=1 THEN CAST(UR.Role_ToDate as DateTime) ELSE NULL End as ValidToDate,null as Company,
			NULL AS Module, NULL AS SubModule,NULL as Remarks 
			FROM SAPRoleInfoSAPUserinfo UR INNER JOIN   DI_SAP_UserInfo U on UR.SAPUserinfo_Id = U.Id  
			INNER JOIN DI_SAP_ROLEINFO R on UR.SAPRoleInfo_Id = R.Id 
			INNER JOIN DI_M_AccountReconcilation AR ON U.ID = AR.EndpointUserId 
            WHERE AR.ID = @ACCOUNTRECONID AND  AR.EndpointSystemId=@ENDPOINTSYSTEMID  AND  
			UR.EndpointSystemId=@ENDPOINTSYSTEMID AND UR.IsDirectlyAttached = 0 and U.EndPointSystemId=@ENDPOINTSYSTEMID AND 
			R.EndPointSystemId=@ENDPOINTSYSTEMID

END