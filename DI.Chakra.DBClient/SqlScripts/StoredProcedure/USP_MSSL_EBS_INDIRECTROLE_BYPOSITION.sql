CREATE PROC DBO.USP_MSSL_EBS_INDIRECTROLE_BYPOSITION
(
@ENDPOINTSYSTEMID BIGINT,
@USERNAME VARCHAR(128),
@POSITIONCODE VARCHAR(MAX)=''
)
AS
BEGIN

		SELECT R.Id,R.EndPointSystemId,U.Id as EndpointUserId,R.ROLE_CODE as BusinessRole,R.ROLE_DESC as Description,CASE WHEN ISDATE(UR.Role_ToDate)=1 THEN 
		CAST(UR.Role_ToDate as DateTime) ELSE NULL End as ValidToDate,null as Company,NULL AS Module, NULL AS SubModule,NULL as Remarks
		FROM DI_SAP_SAPHRP1001 H inner join DI_SAP_ROLEINFO R on H.RelatedObjectCode = R.ROLE_CODE INNER JOIN SAPRoleInfoSAPUserinfo UR on R.Id = UR.SAPRoleInfo_Id
		INNER JOIN DI_SAP_UserInfo U on UR.SAPUserinfo_Id = U.Id
		WHERE  H.ActualObjectCode=@POSITIONCODE and H.RelatedObjectType='AG'  AND 
		U.UserLogonName = @USERNAME AND  H.EndpointSystemId=@ENDPOINTSYSTEMID AND  
		UR.EndpointSystemId=@ENDPOINTSYSTEMID AND UR.IsDirectlyAttached =0    AND 
		U.EndPointSystemId=@ENDPOINTSYSTEMID AND R.EndPointSystemId=@ENDPOINTSYSTEMID

END