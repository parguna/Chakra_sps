        #region Method
        public void delete()
        {
            if (!ContextObjectId.HasValue)
            {
                MasterPage.ShowAlert(AlertType.Error, "Please select an item.");
                return;
            }
            try
            {
                DomainApiClient<Dto.ApproverExceptionInfo>.DeleteById(ContextObjectId.Value);
                var sess = new SessionStatusImpl();
                DILog.UILogger.WriteLog(sess.User.Id, LogLevelType.Info, "Deleted by " + sess.User.UserName);
                Session["ADXLMessage"] = "Record deleted successfully.";
                reloadDatasource = true;
                string redirectTarget = Page.Request.Url.PathAndQuery;
                if (DI.Chakra.Infrastructure.UtilityMethods.IsLocalUrl(redirectTarget))
                    Page.Response.Redirect(redirectTarget, true);
                else
                    Page.Response.Redirect("~/Default.aspx", true);
            }
            catch (Exception)
            {
                MasterPage.ShowAlert(AlertType.Error, "ApproverExceptionInfo cannot be deleted.");
            }
        }

        void upsert()
        {
            Dto.IXLData xldata;
            var editableItem = selectedDataItem;

            long id = 0;
            try
            {
                id = Convert.ToInt64(editableItem.GetDataKeyValue("Id"));
            }
            catch (Exception)
            {

            }

            Hashtable values = new Hashtable();
            string successMessage = string.Empty;
            bool editMode = false;
            string validationMessage = string.Empty;
            if (id > 0)
            {
                editMode = true;
                GridEditableItem item = grdInvalidEntries.EditItems[0] as GridEditableItem;
                xldata = PopulateData(item, id, out validationMessage);
                successMessage = "Record updated successfully.";
            }
            else
            {
                editMode = false;
                editableItem = grdInvalidEntries.MasterTableView.GetInsertItem();
                xldata = PopulateData(editableItem, id, out validationMessage);
                successMessage = "Record inserted successfully.";
            }

            if (!string.IsNullOrWhiteSpace(validationMessage))
            {
                MasterPage.ShowAlert(AlertType.Error, validationMessage);
                return;
            }

            Dictionary<string, string> parameterProcess = new Dictionary<string, string>();
            parameterProcess.Add("templateName", XLTemplates.ApprovalException.ToString());
            parameterProcess.Add("isEditMode", editMode.ToString());
            var datas = DomainApiClient<Dto.IXLData>.GetByAction<IList<DI.Chakra.Dto.IXLData>>(DomainApiAction.XLProcessor.XLData.ProcessXLData, parameterProcess, xldata);
            reloadDatasource = true;
            if (datas != null && datas.Count > 0)
            {
                string hasvalue = datas.First().ValidationMessage;
                if (string.IsNullOrWhiteSpace(hasvalue))
                {
                    Session["ADXLMessage"] = successMessage;
                    string redirectTarget2 = Page.Request.Url.PathAndQuery;
                    if (DI.Chakra.Infrastructure.UtilityMethods.IsLocalUrl(redirectTarget2))
                        Page.Response.Redirect(redirectTarget2, true);
                    else
                        Page.Response.Redirect("~/Default.aspx", true);
                    return;
                }
                else
                {
                    MasterPage.ShowAlert(AlertType.Error, hasvalue);
                    //e.Canceled = true;
                    return;
                }
            }
        }
        private Dto.ApproverExceptionInfo PopulateData(GridEditableItem editableItem, long id, out string validationMsg)
        {
            var existingData = DomainApiClient<Dto.ApproverExceptionInfo>.GetById(id);
            Hashtable values = new Hashtable();
            editableItem.ExtractValues(values);
            if (existingData != null)
            {
                existingData.Person = (string)values["Person"];
                existingData.Approver = (string)values["Approver"];
                var approvallevel = (string)values["ApprovalLevel"];
                if (approvallevel == "1" || approvallevel == "2")
                {
                    existingData.ApprovalLevel = Convert.ToInt16(approvallevel);
                    validationMsg = "";
                }
                else
                {
                    validationMsg = "Approver Level Should be 1 and 2";
                    return new Dto.ApproverExceptionInfo();
                }
                return existingData;
            }
            else
            {
                Dto.ApproverExceptionInfo xldata = new Dto.ApproverExceptionInfo();
                xldata.Person = (string)values["Person"];
                xldata.Approver = (string)values["Approver"];
                var approvallevel = (string)values["ApprovalLevel"];
                if (approvallevel == "1" || approvallevel == "2")
                {
                    xldata.ApprovalLevel = Convert.ToInt16(approvallevel);
                    validationMsg = "";
                }
                else
                {

                    validationMsg = "Approver Level Should be 1 and 2";
                    xldata = new Dto.ApproverExceptionInfo();
                }
                return xldata;
            }
        }
