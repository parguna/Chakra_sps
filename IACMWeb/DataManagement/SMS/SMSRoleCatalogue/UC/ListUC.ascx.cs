        protected void FilterLevel1ApproverType_SelectedIndexChanged(object sender, RadComboBoxSelectedIndexChangedEventArgs e)
        {

            RadComboBox combo = sender as RadComboBox;
            ViewState[combo.ID] = combo.SelectedValue;
            string ColumnName = combo.ID;
            var expression = string.Empty;
            var value = combo.SelectedItem.Text;
            var colName = string.Empty;
            if (combo.SelectedValue.ToString() != "All")
            {
                if (ColumnName.Equals("Level1ApproverType"))
                {
                    colName = "Level1ApproverTypeString";
                }
                else if (ColumnName.Equals("Level2ApproverType"))
                {
                    colName = "Level2ApproverTypeString";
                }
                else if (ColumnName.Equals("Level3ApproverType"))
                {
                    colName = "Level3ApproverTypeString";
                }
                //string ColumnName = "MatrixType";
                expression = String.Format(@"(iif({0} == null, """", {1}).ToString() = (""{2}""))", ColumnName, colName, e.Text);
                //string filterExpression = "([" + "MatrixType" + "] = '" + e.Text + "')";
                if (!string.IsNullOrWhiteSpace(grdInvalidEntries.MasterTableView.FilterExpression))
                {
                    expression = grdInvalidEntries.MasterTableView.FilterExpression +" AND " + expression;
                }
                grdInvalidEntries.MasterTableView.FilterExpression = expression;
            }
            else
            {
                grdInvalidEntries.MasterTableView.FilterExpression = string.Empty;
            }
            //BindValidEntriesGrid();
            grdInvalidEntries.Rebind();
        }
